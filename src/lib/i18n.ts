export type M1Messages = Record<keyof typeof ZH_M1, string>;
export type AllMessages = LocaleMessages & M1Messages;
export type MessageKey = keyof AllMessages;

const EN_ALL: AllMessages = { ...EN, ...EN_M1 };
const MESSAGES: Record<Lang, AllMessages> = { zh: { ...ZH, ...ZH_M1 }, en: EN_ALL };

export function isLang(value: unknown): value is Lang {
  return value === 'zh' || value === 'en';
}

export function getMessages(lang: Lang): AllMessages {
  return MESSAGES[lang];
}

export function t(lang: Lang, key: MessageKey): string {
  const messages = getMessages(lang);
  return messages[key] ?? EN_ALL[key] ?? key;
}

/** 帶變數的文案：把 {name} 形式的佔位符換成 vars 的值。 */
export function tf(lang: Lang, key: MessageKey, vars: Record<string, string | number>): string {
  return t(lang, key).replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function toggleLang(lang: Lang): Lang {
  return lang === 'zh' ? 'en' : 'zh';
}

export const LOCALE_OPTIONS: Lang[] = ['zh', 'en'];
